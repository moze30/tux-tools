const wchar_t* dxApiLabel(DxApi api) {
    switch (api) {
        case DxApi::Dx9: return L"Direct3D 9";
        case DxApi::Dx10: return L"Direct3D 10";
        case DxApi::Dx11: return L"Direct3D 11";
        case DxApi::Dx12: return L"Direct3D 12";
    }
    return L"";
}

